export function Barcode({ value, height = 56, scale = 2, className = "" }) {
  const codes = [104];
  for (const ch of String(value)) {
    const v = ch.charCodeAt(0) - 32;
    codes.push(v >= 0 && v < 95 ? v : 0);
  }
  let sum = codes[0];
  for (let i = 1; i < codes.length; i++) sum += codes[i] * i;
  codes.push(sum % 103, 106);
  const rects = [];
  let x = 10 * scale;
  for (const c of codes) {
    const pat = PATTERNS[c];
    for (let i = 0; i < pat.length; i++) {
      const w = Number(pat[i]) * scale;
      if (i % 2 === 0) rects.push({ x, w });
      x += w;
    }
  }
  const total = x + 10 * scale;
  return (
    <svg viewBox={`0 0 ${total} ${height}`} width={total} height={height}
      className={`max-w-full ${className}`} role="img" aria-label={`Barcode ${value}`}>
      <rect x="0" y="0" width={total} height={height} fill="white" />
      {rects.map((r, i) => (
        <rect key={i} x={r.x} y="0" width={r.w} height={height} fill="black" />
      ))}
    </svg>
  );
}
